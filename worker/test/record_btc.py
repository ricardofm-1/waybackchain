#!/usr/bin/env python3
"""Record mempool.space responses for the Bitcoin module's unit tests.

Saves every response the Worker's walk would request for each
(address, date) case under test/fixtures/btc/, plus expected.rs for the busy
address (computed here, independently of the Rust code). Run rarely: it makes
live calls and mempool.space rate-limits quickly.
"""
import calendar, datetime, json, pathlib, time, urllib.request

API = "https://mempool.space/api"
OUT = pathlib.Path(__file__).parent / "fixtures" / "btc"
EMPTY = "1JG56Dftg8Ygy4XZR7eZ4e2fZxMCsaHEFd"
LIGHT = "14taMumBrvWCVw214fExgvX1FdmiK2FFy6"
BUSY = "1A1zP1eP5QGefi2DMPTfTL5SLmv7DivfNa"

cache = {}

def get(path):
    if path in cache:
        return cache[path]
    time.sleep(1.2)
    req = urllib.request.Request(API + path, headers={"User-Agent": "waybackchain-fixtures"})
    data = json.load(urllib.request.urlopen(req))
    cache[path] = data
    (OUT / (path.lstrip("/").replace("/", "__") + ".json")).write_text(json.dumps(data, indent=1))
    return data

def cutoff(date):
    d = datetime.date.fromisoformat(date)
    return calendar.timegm(d.timetuple()) + 86399

def delta(tx, addr):
    recv = sum(o["value"] for o in tx["vout"] if o.get("scriptpubkey_address") == addr)
    sent = sum(i["prevout"]["value"] for i in tx["vin"] if i.get("prevout") and i["prevout"].get("scriptpubkey_address") == addr)
    return recv - sent

def walk(addr, date, max_txs=2000):
    """Fetch exactly what the Worker would; return the balance (or None)."""
    t = cutoff(date)
    get(f"/v1/mining/blocks/timestamp/{t}")
    s = get(f"/address/{addr}")["chain_stats"]
    bal = s["funded_txo_sum"] - s["spent_txo_sum"]
    if s["tx_count"] == 0:
        return bal
    after, last = 0, None
    while True:
        page = get(f"/address/{addr}/txs/chain" + (f"/{last}" if last else ""))
        for tx in page:
            if tx["status"]["block_time"] <= t:
                return bal
            after += 1
            if after > max_txs:
                return None
            bal -= delta(tx, addr)
        if len(page) < 25:
            return bal
        last = page[-1]["txid"]

OUT.mkdir(parents=True, exist_ok=True)
for d in ["2015-06-01", "2024-01-01"]:
    walk(EMPTY, d)
for d in ["2023-12-31", "2024-01-01", "2024-01-02"]:
    print(LIGHT, d, walk(LIGHT, d))
assert walk(BUSY, "2015-06-01", max_txs=30) is None

# Busy, recent: pick a date whose cutoff falls inside the first two pages.
p1 = get(f"/address/{BUSY}/txs/chain")
p2 = get(f"/address/{BUSY}/txs/chain/{p1[-1]['txid']}")
txs = p1 + p2
pivot = datetime.datetime.utcfromtimestamp(txs[30]["status"]["block_time"]).date()
recent = (pivot + datetime.timedelta(days=0)).isoformat()
t = cutoff(recent)
assert any(tx["status"]["block_time"] <= t for tx in txs), "cutoff not inside recorded pages"
info = get(f"/address/{BUSY}")["chain_stats"]
expected = info["funded_txo_sum"] - info["spent_txo_sum"] - sum(delta(tx, BUSY) for tx in txs if tx["status"]["block_time"] > t)
assert walk(BUSY, recent) == expected
(OUT / "expected.rs").write_text(
    "// Generated by test/record_btc.py. Do not edit.\n"
    f'pub const RECENT_DATE: &str = "{recent}";\n'
    f"pub const RECENT_BALANCE: u128 = {expected};\n"
)
print("busy", recent, expected)
